//   * TLBRD：按 TLBIDX.Index 读表项到 TLBEHI/TLBELO0/TLBELO1/ASID；
//   * TLBWR：按 TLBIDX.Index 写表项；TLBFILL：写入随机/替换位置；
//   * INVTLB：按 invtlb_op 作废相应表项；
//   * 取指/访存需要经过 TLB 做虚实地址转换（本实验仅要求 TLB 指令本身可工作，
